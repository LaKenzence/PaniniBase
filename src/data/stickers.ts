// ─── Helpers ─────────────────────────────────────────────────────────────────

const mkPlayer = (
  editionId: string, n: number, name: string, team: string,
  flag: string, colKey: string, pos: 'Gardien' | 'Défenseur' | 'Milieu' | 'Attaquant',
  jersey: number, club: string, playerKey?: string, isShiny = false
): Sticker => ({
  id: `${editionId}-${n}`,
  editionId,
  number: n,
  category: isShiny ? 'shiny' : 'player',
  isShiny,
  player: { name, nationality: team, flag, position: pos, jerseyNumber: jersey, club, colKey, playerKey },
  teamName: team,
});

